/**
 * The level is authored as ASCII chunks that are concatenated horizontally.
 * Every chunk is CHUNK_H rows tall; rows are padded/truncated to the chunk's
 * declared width when the level is parsed.
 *
 * Layout rule of thumb, so the whole level stays walkable: floor gaps are at
 * most 4 tiles wide and each platform sits at most 3 rows above the surface
 * you jump from - comfortably inside the hero's jump arc.
 *
 *   .  empty            #  stone block        =  earth block
 *   -  one-way platform ^  spikes             L/l lava surface / body
 *   G  boss arena gate  S  seal (opens when the knight falls)
 *   P  player spawn      B  boss spawn         O  gate home (goal)
 *   s  slime            b  bat                k  skeleton     m  dark mage
 *   $  gem              H  heart              C  checkpoint
 *   T  torch            X  crystal            M/V moving platform (h/v)
 */

export const CHUNK_H = 22;

export interface Chunk {
  width: number;
  rows: string[];
}

const c = (width: number, rows: string[]): Chunk => ({ width, rows });

