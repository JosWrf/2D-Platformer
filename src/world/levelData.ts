/**
 * The level is authored as ASCII chunks that are concatenated horizontally.
 * Every chunk is CHUNK_H rows tall; rows are padded/truncated to the chunk's
 * declared width when the level is parsed.
 *
 * Layout rule of thumb, so the whole level stays walkable: floor gaps are at
 * most 4 tiles wide and each platform sits at most 3 rows above the surface
 * you jump from - comfortably inside the hero's jump arc.
 *
 *   .  empty            #  stone block        =  earth block
 *   -  one-way platform ^  spikes             L/l lava surface / body
 *   G  boss arena gate  S  seal (opens when the knight falls)
 *   P  player spawn      B  boss spawn         O  gate home (goal)
 *   s  slime            b  bat                k  skeleton     m  dark mage
 *   $  gem              H  heart              C  checkpoint
 *   T  torch            X  crystal            M/V moving platform (h/v)
 *   |  arena ward (see warded() below)
 *   A  Ankhor, the temple colossus   I  Ignivor, the ember wyrm
 *   D  Vesperon, the blood lord      U  Gierschlund, the greedy chest
 *   N  Arachna, the web queen        E  Umbra, the hero's shadow
 *   R  Grimmzahn, the boar           J  Sol and Luna, the star twins
 *   F  Tickmar, the clockwork          j  Maskarill, the jester
 *   n  Nyktos, the light-eater        y  Grauwacht, the gargoyle
 */

export const CHUNK_H = 22;

export interface Chunk {
  width: number;
  rows: string[];
}

/**
 * Builds a chunk and refuses a malformed one.
 *
 * A chunk one row short does not fail anywhere: it simply lifts its own floor
 * a tile above its neighbours', and the seam is easy to miss on a dark
 * background. That happened to RIFT_SHARDS while fixing a platform in it, and
 * it shipped. Throwing here means the build stops instead.
 */
const c = (width: number, rows: string[]): Chunk => {
  if (rows.length !== CHUNK_H) {
    throw new Error(`Chunk has ${rows.length} rows, expected ${CHUNK_H}`);
  }
  const wrong = rows.findIndex((r) => r.length !== width);
  if (wrong >= 0) {
    throw new Error(`Chunk row ${wrong} is ${rows[wrong].length} wide, expected ${width}`);
  }
  return { width, rows };
};

/**
 * Puts a ward into the given columns of a chunk, from the top row down to the
 * row the arena floor stands on.
 *
 * A ward is a boss arena's door: the one behind the hero comes down when the
 * fight begins, the one ahead of him stands until the boss has fallen. It runs
 * the full height on purpose - a four-tile door in an open field is a door
 * that gets jumped over, and then the boss is optional again. Only empty cells
 * are warded; rock stays rock, so an interior keeps its ceiling. Anything else
 * in the way (a platform, a spawn) is a mistake in the chunk, and stops the
 * build rather than being quietly overwritten.
 */
const warded = (chunk: Chunk, columns: number[], bottomRow = 17): Chunk => {
  const rows = chunk.rows.map((row, ty) => {
    if (ty > bottomRow) return row;
    const cells = row.split('');
    for (const tx of columns) {
      if (cells[tx] === '.') cells[tx] = '|';
      else if (cells[tx] !== '#' && cells[tx] !== '=') {
        throw new Error(`Ward at column ${tx}, row ${ty} would cover '${cells[tx]}'`);
      }
    }
    return cells.join('');
  });
  return c(chunk.width, rows);
};

