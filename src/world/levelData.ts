/** World x, in pixels, at which a chunk begins. */
function startOf(chunk: Chunk): number {
  let tiles = 0;
  for (const other of LEVEL_CHUNKS) {
    if (other === chunk) return tiles * 32;
    tiles += other.width;
  }
  throw new Error('Chunk is not in the level');
}

